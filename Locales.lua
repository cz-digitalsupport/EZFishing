-- Englisch als Basis, danach die Sprache des Clients darüberlegen
for key, value in pairs(translations.enUS) do
    L[key] = value
end

local locale = GetLocale()
local localized = translations[locale]
if localized and localized ~= translations.enUS then
    for key, value in pairs(localized) do
        if key ~= "POOL_PATTERNS" then
            L[key] = value
        end
    end
end

-- Fischschwarm-Namen: Englisch immer, plus Clientsprache
local poolPatterns = {}
for _, pattern in ipairs(translations.enUS.POOL_PATTERNS) do
    table.insert(poolPatterns, pattern)
end
if localized and localized ~= translations.enUS then
    for _, pattern in ipairs(localized.POOL_PATTERNS) do
        table.insert(poolPatterns, pattern)
    end
end
L.POOL_PATTERNS = poolPatterns
